#pragma once
#include <Arduino.h>

// =============================================================================
//  Реестр модулей и универсальный драйвер списочного меню.
//
//  Раньше каждое верхнеуровневое меню (главное, игры, bluetooth) было
//  скопировано вручную и рассинхронизировано в 3-4 местах (массив подписей,
//  switch-диспетчер, forward-декларации, глобальный ITEMS). Теперь меню — это
//  таблица MenuItem[], а runMenu() рисует её и вызывает выбранный пункт.
//
//  Добавить пункт = написать функцию-экран `void screen()` и дописать одну
//  строку в таблицу. Подробности — в docs/03_ADDING_MODULES.md.
// =============================================================================

struct MenuItem {
  const char* name;   // подпись в меню
  void (*run)();       // функция-экран (блокирующая, возвращает управление по back)
};

// Универсальный драйвер списочного меню (>8 пунктов прокручиваются постранично).
//   items       — таблица пунктов
//   count       — число пунктов (курсор ограничивается именно им — нет "пустых" строк)
//   showVoltage — рисовать напряжение батареи в правом верхнем углу (главное меню)
//   allowBack   — реагировать ли на back выходом (false — для корневого меню,
//                 которое никогда не выходит)
void runMenu(const MenuItem* items, uint8_t count,
             bool showVoltage = false, bool allowBack = true);
